"""The owner's model scripts (launcher/upload-models.sh, package-models.sh, export-models.sh) write and check each
model's Modelfile through one function, modelfile_of: Ollama's own Modelfile with FROM ./<model>.gguf and its PARAMETER
lines in A-Z order. 16 Nov: Ollama 0.40.11 printed three of the four tested models' settings in another order (the same
settings), so the scripts refused them; the order is now set before the SHA-256 is checked."""
import hashlib
import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

LAUNCHER = Path(__file__).resolve().parent.parent / "launcher"
SCRIPTS = ("upload-models.sh", "package-models.sh", "export-models.sh")
# flip-reader-5's Modelfile as Ollama 0.40.11 prints it, with its settings in the order Ollama printed flip-kinds-1's
# on 16 Nov (the order Ollama keeps for that model), not A-Z
PRINTOUT = (
    '# Modelfile generated by "ollama show"\n'
    '# To build a new Modelfile based on this, replace FROM with:\n'
    '# FROM flip-reader-5:latest\n'
    '\n'
    'FROM /Users/someone/.ollama/models/blobs/sha256-b946131ba11fc159fdc1cf683dab0d3b9c4a64cb80dd9726b1b4208b8632bae1\n'
    'TEMPLATE """{{- range $i, $_ := .Messages }}\n'
    '{{- $last := eq (len (slice $.Messages $i)) 1 }}\n'
    '{{- if or (eq .Role "user") (eq .Role "system") }}<start_of_turn>user\n'
    '{{ .Content }}<end_of_turn>\n'
    '{{ if $last }}<start_of_turn>model\n'
    '{{ end }}\n'
    '{{- else if eq .Role "assistant" }}<start_of_turn>model\n'
    '{{ .Content }}{{ if not $last }}<end_of_turn>\n'
    '{{ end }}\n'
    '{{- end }}\n'
    '{{- end }}"""\n'
    'PARAMETER top_k 64\n'
    'PARAMETER top_p 0.95\n'
    'PARAMETER stop <end_of_turn>\n'
    'PARAMETER temperature 1\n'
    'LICENSE "Gemma is provided under and subject to the Gemma Terms of Use found at ai.google.dev/gemma/terms.\n'
    'Modified: Gemma 3 4B instruct, LoRA fine-tuned and merged for FlipAssist (round 5, the last round: iPhone, Samsung, MacBook; UK, US, Canada)."\n'
    '\n'
)


def function(script):
    text = (LAUNCHER / script).read_text(encoding="utf-8")
    return re.search(r"^modelfile_of\(\) \{\n.*?^\}\n", text, re.S | re.M).group(0)


def pinned_modelfile(model):
    """the Modelfile SHA-256 that get-models.sh holds for the tested model"""
    text = (LAUNCHER / "get-models.sh").read_text(encoding="utf-8")
    return dict(re.findall(r"(flip-[\w-]+)\) echo ([0-9a-f]{64})", text[text.index("tested_modelfile()"):]))[model]


def run(tmp_path, printout):
    """modelfile_of flip-reader-5, with an ollama on PATH that prints the given Modelfile"""
    (tmp_path / "bin").mkdir()
    (tmp_path / "tmp").mkdir()
    (tmp_path / "printout").write_text(printout, encoding="utf-8")
    ollama = tmp_path / "bin" / "ollama"
    ollama.write_text('#!/bin/sh\n[ "$*" = "show --modelfile flip-reader-5" ] || exit 1\ncat "%s"\n' % (tmp_path / "printout"))
    ollama.chmod(0o755)
    (tmp_path / "fn.sh").write_text(function("upload-models.sh"), encoding="utf-8")
    env = dict(os.environ, PATH=f"{tmp_path / 'bin'}{os.pathsep}{os.environ['PATH']}", TMPDIR=str(tmp_path / "tmp"))
    out = subprocess.run(["sh", "-c", '. "$0" && modelfile_of flip-reader-5', str(tmp_path / "fn.sh")],
                         env=env, capture_output=True, check=True).stdout
    assert not list((tmp_path / "tmp").iterdir())  # its working copy is gone
    return out


def test_the_three_scripts_have_the_same_function():
    assert function("upload-models.sh") == function("package-models.sh") == function("export-models.sh")


def test_each_script_checks_and_writes_through_it():
    for script in SCRIPTS:
        text = (LAUNCHER / script).read_text(encoding="utf-8")
        assert 'modelfile_of "$model"' in text, script
        # Ollama's printout is no longer hashed or written as it comes
        assert not re.search(r'ollama show --modelfile "\$model" \| sed "s#\^FROM', text), script
    upload = (LAUNCHER / "upload-models.sh").read_text(encoding="utf-8")
    assert 'modelfile_of "$model" > "$model.Modelfile"' in upload
    for script in ("package-models.sh", "export-models.sh"):
        assert 'got=$(modelfile_of "$model" | shasum -a 256' in (LAUNCHER / script).read_text(encoding="utf-8")


@pytest.mark.skipif(os.name == "nt" or not shutil.which("sh"), reason="the Mac scripts run in sh")
def test_settings_out_of_order_give_the_tested_modelfile(tmp_path):
    out = run(tmp_path, PRINTOUT)
    assert hashlib.sha256(out).hexdigest() == pinned_modelfile("flip-reader-5")
    text = out.decode("utf-8")
    assert [l.split()[1] for l in text.splitlines() if l.startswith("PARAMETER ")] == ["stop", "temperature", "top_k", "top_p"]
    assert "FROM ./flip-reader-5.gguf\n" in text and "sha256-" not in text


@pytest.mark.skipif(os.name == "nt" or not shutil.which("sh"), reason="the Mac scripts run in sh")
def test_settings_already_in_order_come_out_as_printed(tmp_path):
    lines = PRINTOUT.split("\n")
    at = [i for i, line in enumerate(lines) if line.startswith("PARAMETER ")]
    lines[at[0]:at[-1] + 1] = sorted(lines[at[0]:at[-1] + 1])
    in_order = "\n".join(lines)
    out = run(tmp_path, in_order).decode("utf-8")
    assert out == re.sub(r"(?m)^FROM .*$", "FROM ./flip-reader-5.gguf", in_order)
